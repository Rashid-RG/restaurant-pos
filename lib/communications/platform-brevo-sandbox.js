/**
 * Explicit Brevo sandbox transport adapter for Platform Communication Center.
 * Never registered in server startup or called by any HTTP route.
 *
 * In addition to the queue's own staging gates, require a separate provider-send
 * gate. It accepts ONLY exact addresses in PLATFORM_COMMUNICATIONS_TEST_EMAILS.
 * A response indicates Brevo API acceptance, NOT mailbox delivery.
 */
import {sendBrevoEmail,brevoSettings} from '../brevo-email.js';
import {normalizeSandboxAddress,sandboxEmailAllowed} from './platform-email-queue.js';

export function sandboxBrevoReady(env={}){
  return Boolean(
    sandboxEmailAllowed(
      [...String(env.PLATFORM_COMMUNICATIONS_TEST_EMAILS||'').split(',')][0],env
    ) &&
    env.PLATFORM_COMMUNICATIONS_BREVO_SEND_ENABLED==='true' &&
    env.PLATFORM_COMMUNICATIONS_EMAIL_TRANSPORT==='brevo_sandbox' &&
    brevoSettings(env).configured
  );
}

/**
 * Pass a fake fetcher in tests. A non-allowlisted address never reaches fetch.
 * An invocation must be made by a separately approved, manually invoked runner.
 */
export function createSandboxBrevoSender({env={},fetcher=fetch}={}){
  return async ({to,subject,text,idempotencyKey})=>{
    const address=normalizeSandboxAddress(to);
    if(!sandboxBrevoReady(env)||!address||!sandboxEmailAllowed(address,env)){
      return {success:false,reason:'SANDBOX_PROVIDER_DISABLED_OR_RECIPIENT_BLOCKED'};
    }
    if(typeof subject!=='string'||subject.length<3||subject.length>140||
       typeof text!=='string'||text.length<5||text.length>10000){
      return {success:false,reason:'INVALID_NOTICE'};
    }
    // Idempotency keys are generated by the queue; included for future provider
    // reconciliation. Brevo's current sender does not enforce idempotency.
    if(typeof idempotencyKey!=='string'||idempotencyKey.length<5){
      return {success:false,reason:'MISSING_DELIVERY_IDENTITY'};
    }
    const result=await sendBrevoEmail({to:address,subject,text,env,fetcher});
    return result?.success===true
      ?{success:true,provider:'brevo',providerMessageId:result.messageId,accepted:true}
      :{success:false,reason:'BREVO_UNCONFIRMED'};
  };
}
